# 自动假名质检
kana_pattern = re.compile(r'[\u3040-\u309F\u30A0-\u30FF]')
def check_kana(obj):
    found = []
    if isinstance(obj, str):
        m = kana_pattern.findall(obj)
        if m: found.extend(m)
    elif isinstance(obj, dict):
        for k, v in obj.items(): found.extend(check_kana(v))
    elif isinstance(obj, list):
        for it in obj: found.extend(check_kana(it))
    return found

